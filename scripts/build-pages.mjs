import { cp, mkdir, rm, copyFile, readFile, writeFile } from "node:fs/promises";
import { runInNewContext } from 'node:vm';

const publicDir = new URL("../public/", import.meta.url);
const distDir = new URL("../dist/", import.meta.url);
const context = { window: {}, URL, document: { currentScript: { src: 'https://quiz.example/config.js' } } };
runInNewContext(await readFile(new URL('config.js', publicDir), 'utf8'), context);
const approvedZips = context.window.CONFIG.zipVerification.allowedZipCodes.split(',').map(zip => zip.trim()).filter(Boolean);
if (!approvedZips.length || approvedZips.some(zip => !/^\d{5}$/.test(zip))) throw new Error('Invalid approved ZIP configuration');
await writeFile(new URL('../functions/_lib/serviceArea.js', import.meta.url), '// Generated by build-pages.mjs from CONFIG.zipVerification; edit public/config.js.\nexport const allowedZipCodes = new Set(' + JSON.stringify(approvedZips) + ');\n');

await rm(distDir, { recursive: true, force: true });
await cp(publicDir, distDir, { recursive: true });

for (const route of ["a", "b", "c", "d", "e"]) {
  const routeDir = new URL(`${route}/`, distDir);
  await mkdir(routeDir, { recursive: true });
  await copyFile(new URL("index.html", distDir), new URL("index.html", routeDir));
}

console.log("Built Cloudflare Pages output with /a, /b, /c, /d, and /e route entries.");
